"""Generate the integrated 048 -> 052 module upgrade; never deploys it."""
from pathlib import Path
root=Path(__file__).resolve().parents[1]
files=sorted((root/'supabase/migrations').glob('202611240000*.sql'))
assert len(files)==4,'Expected the reviewed 049-052 migration set'
header="""-- Generated by tools/build_remaining_owner_provider_upgrade.py.
-- Back up the Integration project, review, and apply only after 047/048.
begin;
do $$ begin
 if not exists(select 1 from public.app_deployment_environment where singleton
   and environment='staging' and project_ref='myetpfavvwuevdcybdes') then
  raise exception 'This upgrade targets the integrated Staging project only';
 end if;
 if not exists(select 1 from supabase_migrations.schema_migrations where version='20261123000048') then
  raise exception 'Integrated cleaning checkpoint migration 048 is required';
 end if;
 if exists(select 1 from supabase_migrations.schema_migrations
   where version in ('20261124000049','20261124000050','20261124000051','20261124000052')) then
  raise exception 'Module upgrade already recorded; verify history before retrying';
 end if;
end $$;
"""
body='\n'.join('-- '+f.name+'\n'+f.read_text(encoding='utf-8') for f in files)
records=',\n'.join(" ('"+f.name.split('_',1)[0]+"','"+f.stem.split('_',1)[1]+"')" for f in files)
tail="\ninsert into supabase_migrations.schema_migrations(version,name) values\n"+records+";\nnotify pgrst,'reload schema';\ncommit;\n"
destination=root/'supabase/deploy/upgrade_remaining_owner_provider.sql'
destination.write_text(header+body+tail,encoding='utf-8')
print(destination)
